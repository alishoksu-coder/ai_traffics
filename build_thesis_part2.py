def set_font(run, name='Times New Roman', size=14, bold=False, italic=False):
    run.font.name = name
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic

def create_report_part2():
    print("Генерация Части 2 диплома (Word / Kazakh)...")
    doc = docx.Document()

    # 1. Настройка полей по ГОСТ
    for section in doc.sections:
        section.top_margin = Cm(2)
        section.bottom_margin = Cm(2)
        section.left_margin = Cm(3)
        section.right_margin = Cm(1.5)

    def add_heading(text, is_chapter=False):
        if is_chapter:
            doc.add_page_break()
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(24)
        p.paragraph_format.space_after = Pt(12)
        run = p.add_run(text)
        set_font(run, size=16, bold=True)
        return p

    def add_subheading(text):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.first_line_indent = Cm(1.25)
        p.paragraph_format.space_before = Pt(18)
        p.paragraph_format.space_after = Pt(6)
        run = p.add_run(text)
        set_font(run, size=14, bold=True)
        return p

    def add_body(text):
        if not text.strip():
            return
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.first_line_indent = Cm(1.25)
        p.paragraph_format.line_spacing = Pt(21)
        run = p.add_run(text)
        set_font(run, size=14)
        return p

    def add_formula(text, number):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(6)
        p.paragraph_format.space_after = Pt(6)
        run = p.add_run(text)
        set_font(run, size=14, italic=True)
        run2 = p.add_run(f'   ({number})')
        set_font(run2, size=14)
        return p

    def add_placeholder(desc):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(f"\n[ СУРЕТ ОРНЫ / СКРИНШОТ / СХЕМА : {desc} ]\n")
        set_font(run, size=14, bold=True, italic=True)
        run.font.color.rgb = docx.shared.RGBColor(200, 50, 50)

    # ================= ГЛАВА 3. ОБЩЕЕ ОПИСАНИЕ ПРИЛОЖЕНИЯ =================
    add_heading("3 AI Traffic жобасының толық функционалдық сипаттамасы", is_chapter=True)

    add_subheading("3.1 Қосымшаның жалпы архитектурасы мен интерфейсі")
    add_body("AI Traffic жобасы — бұл тек бағыттаушы (навигатор) емес, сонымен қатар нейрондық желілер мен Big Data талдауына негізделген «ақылды қала» (Smart City) концепциясының толыққанды экожүйесі. Қосымшаның негізгі мақсаты — пайдаланушыларға жоғары сапалы, интуитивті түсінікті UX/UI дизайнымен бірге, кез келген бағыт бойынша ең қауіпсіз әрі кедергісіз жолды ұсыну.")
    add_body("Мобильді қосымша Flutter фреймворкі негізінде жасалып, Glassmorphism (әйнек тәрізді мөлдір) дизайн стилінде жүзеге асырылған. Бұл дизайн пайдаланушыға картаны толық көруге мүмкіндік бере отырып, ақпараттық панельдердің визуалды салмағын азайтады. Жүйе Dark Mode (түнгі режим) және Light Mode (күндізгі режим) ауысуларын толық қолдайды.")
    
    add_placeholder("Мобильді қосымшаның басты экраны (Glassmorphism, Карта, Іздеу жолағы)")

    add_subheading("3.2 Пайдаланушының жеке кабинеті және әлеуметтік функциялар")
    add_body("Навигациядан бөлек, жүйеде толыққанды авторизация (Supabase PostgreSQL арқылы) бар. Пайдаланушылар өз аккаунттарын құра алады, көлік профилін баптай алады және ең бастысы — «Достар» (Friends) әлеуметтік модулін пайдалана алады.")
    add_body("«Достар» модулі арқылы пайдаланушылар бір-бірін электрондық пошта (E-mail) арқылы іздеп, дос болуға өтінім жібере алады. Өтінім расталғаннан кейін, олар картадан бір-бірінің нақты уақыттағы орналасқан жерін көре алады. Бұл функция отбасы мүшелерінің қауіпсіздігін бақылау немесе достармен ортақ кездесулерді жоспарлау үшін өте тиімді.")
    
    add_placeholder("«Достар» экраны: достыққа шақыру және достардың картадағы нүктелері")

    # ================= ГЛАВА 4. ДАТАСЕТ И ЦИФРОВОЙ КЛОН =================
    add_heading("4 «Цифрлық Егіз» (Digital Twin) инклюзивті ортаны модельдеу", is_chapter=True)

    add_subheading("4.1 Есіл ауданының микро-датасетін генерациялау")
    add_body("Қазіргі заманғы Google Maps немесе 2GIS сияқты алып корпорациялардың навигаторларында бір үлкен кемшілік бар — олар жолды тек физикалық «сызық» (polyline) ретінде қабылдайды. Олар жолдың микро-инфрақұрылымын (пандустардың болуы, баспалдақтар, асфальт немесе тас төсеніш сапасы) ескермейді. AI Traffic жобасының негізгі ғылыми жетістіктерінің бірі — қаланың «Цифрлық Егізін» (Digital Twin) жасау.")
    add_body("Дипломдық жұмыс аясында Астана қаласының Есіл ауданының (Бәйтеректен Хан Шатырға дейінгі инфрақұрылым) жоғары дәлдіктегі микро-датасеті нөлден бастап бағдарламалық түрде генерацияланды. Python сценарийімен (generate_yesil_dataset.py) 100x100 тор көлемінде масштабталған граф құрылды. Толық датасеттің сипаттамасы:")
    
    add_placeholder("Python сценарийінің датасет генерациялау кезіндегі терминал логтары (10 000 узел)")

    add_body("- Географиялық түйіндер (Nodes): 10 000 қиылыс және жаяу жүргіншілер нүктелері.")
    add_body("- Инфрақұрылымдық байланыстар (Edges): 39 600 тротуар мен жол бөліктері.")
    add_body("Әрбір тротуар бөлігі келесі бірегей параметрлерді сақтайды:")
    add_body("1. has_ramp (boolean) — бордюрда арбаға арналған арнайы тегіс түсірілім (пандус) бар-жоғы.")
    add_body("2. stairs_count (int) — осы учаскедегі баспалдақ баспалдақтарының саны (коляскалар үшін өте қауіпті кедергі).")
    add_body("3. surface_quality (int, 1-10) — жолдың сапасы 1-ден 10-ға дейінгі шкаламен (10 – мінсіз асфальт, 3 – шұңқырлы тас жол).")

    add_subheading("4.2 Мүмкіндігі шектеулі жандарға арналған «Кедергісіз» (Barrier-free) режимі")
    add_body("Мобильді қосымшада пайдаланушы үшін арнайы «Кедергісіз» (С коляской/инвалидам) қосқышы қарастырылған. Ол қосылған кезде, жүйе A-Star (A*) эвристикалық іздеу алгоритмін мүлдем жаңа математикалық айыппұлдармен (penalty) іске қосады.")
    add_body("Мәселен, қарапайым пешеход бағыты 100 түйіннен құралып, 1700 метрге созылса, мүгедектер арбасына арналған бағыт құру алгоритмі келесі шарттарды орындайды:")
    add_body("- stairs_count > 0 болса, бұл жол өтуге қатаң тыйым салынған аймақ (barrier) ретінде қабылданады.")
    add_body("- has_ramp == False болса, математикалық бағаға +300 виртуалды метр айыппұл қосылады.")
    add_body("- surface_quality < 5 болса, шұңқырлар үшін қосымша айыппұлдар салынады.")
    
    add_placeholder("A* алгоритмімен салынған кәдімгі жол және Баспалдақтарды айналып өтетін 'Кедергісіз' жол картасының суреттері (Салыстыру)")
    
    add_body("Нәтижесінде, AI алгоритмі коляскаға арналған жолды 116 түйін арқылы (айналма жол) сала отырып, физикалық тұрғыдан 100% қауіпсіз маршрут тауып береді. Бұл біздің жүйені қолданыстағы отандық баламалардан оқшаулайтын негізгі функционал.")

    add_subheading("4.3 «What-If» симуляторы: Диспетчерлік қолмен шектеу")
    add_body("Цифрлық егіз концепциясының тағы бір көрінісі — қала аумағын динамикалық түрде модификациялау. Мобильді қосымшада (әкімшілік рұқсатпен) картадағы кез келген нүктеге ұзақ басу (onLongPress) арқылы «Жолды жабу / Симуляция» триггері іске қосылады.")
    add_body("FastAPI серверіне POST сұрау жіберілгеннен кейін, жүйе сол аймақты «Хотспот» (Hotspot) ретінде белгілейді. Суретті өзгертіп қана қоймай, бағдарлама бүкіл Астана бойынша навигациялық жолдарды қайта құрып, автокөліктерді жасанды пробкадан айналып өтуге мәжбүрлейді.")

    # ================= ГЛАВА 5. LSTM И МАШИННОЕ ОБУЧЕНИЕ =================
    add_heading("5 Нейрожелілік трафикті болжау (LSTM) және Z-Score", is_chapter=True)

    add_subheading("5.1 Нейрондық желі архитектурасын таңдау: Неге LSTM?")
    add_body("Жүйенің аналитикалық ядросы кеңістік-уақыттық деректермен (spatio-temporal data) жұмыс істейді. Тек статистік шешімдерден басқа, біз болашақта енгізуге негізделген терең оқыту архитектурасын — LSTM (Long Short-Term Memory) нейрондық желісін әзірледік.")
    add_body("Қарапайым көп қабатты персептрондардан (MLP) немесе Random Forest алгоритмдерінен айырмашылығы, LSTM затухающий градиент мәселесін шешеді және трафиктің ұзақ мерзімді (апталық ритм) және қысқа мерзімді (соңғы 15 минут) заңдылықтарын еске сақтай алады.")

    add_subheading("5.2 LSTM жасушасының математикалық моделі")
    add_body("LSTM нейрондық желісінің математикалық аппараты 4 негізгі вентильден (gate) тұрады:")
    
    add_body("1) Ұмыту вентилі (Forget Gate): қандай ескі ақпаратты жадтан өшіру керектігін шешеді.")
    add_formula("f_t = σ(W_f · [h_{t-1}, x_t] + b_f)", "13")
    
    add_body("2) Кіріс вентилі (Input Gate): жаңа деректердің қай бөлігін жадқа жазу kerektigin анықтайды.")
    add_formula("i_t = σ(W_i · [h_{t-1}, x_t] + b_i)", "14")
    add_formula("C̃_t = tanh(W_c · [h_{t-1}, x_t] + b_c)", "15")

    add_body("3) Жасуша күйін жаңарту (Cell State Update):")
    add_formula("C_t = f_t * C_{t-1} + i_t * C̃_t", "16")

    add_body("4) Шығыс вентилі (Output Gate): болжамның қорытынды жасырын күйін қалыптастырады.")
    add_formula("o_t = σ(W_o · [h_{t-1}, x_t] + b_o)", "17")
    add_formula("h_t = o_t * tanh(C_t)", "18")
    
    add_body("Мұндағы: x_t — кіріс тензорлар (уақыт, ауа-райы векторы), σ — сигмоидты активация функциясы, ал W және b — нейрожелінің салмақ матрицалары (weights) мен ығысулары (biases).")

    add_placeholder("LSTM Желісінің Архитектуралық Схемасы (UML диаграмма, вход слоя, Hidden Layer 1, Hidden Layer 2, Dense Layer, Dropout)")

    add_subheading("5.3 Аномалия детектор алгоритмі (Z-Score)")
    add_body("Көшедегі күтпеген жағдайларды (ДТП, жол жөндеу) нейрожелі тарихи паттерндерден көре алмайды. Бұл олқылықты жабу үшін жүйеде математикалық Z-бағалау (Z-Score) статистикалық модулі параллель іске қосылады.")
    add_body("Алгоритм соңғы K=10 бақылаудың сырғымалы орташа мәнін (μ_rolling) және стандартты ауытқуын (σ_rolling) табады.")
    
    add_formula("Z = (X_t - μ_rolling) / σ_rolling", "19")

    add_body("Егер алынған Z-мәнінің модулі |Z| > 2.5 болса, бағдарлама математикалық тұрғыдан бұл жүктеменің кездейсоқ емес, төтенше жағдай екенін растайды және «Critical Anomaly» статусын шығарады.")

    # ================= ГЛАВА 6. ЗАКЛЮЧЕНИЕ / ВЫВОДЫ =================
    add_heading("6 Жобаны дамыту перспективалары", is_chapter=True)
    add_body("AI Traffic бағдарламалық-аппараттық кешені болашақта Smart Astana орталық бейнебақылау камералары жүйесімен (Сергек) тікелей интеграциялануға толық дайын архитектураға ие. Мобильді қосымша миллиондаған сұрауларды өңдей алатын бұлтты (Cloud) инфрақұрылымға ауысуы мүмкін. Digital Twin микро-датасет генераторы Астана қаласының ғана емес, Қазақстанның кез келген қаласының инфрақұрылымын есепке алып, инклюзивті ортаны дамытуға үлкен үлес қосады.")

    output_path = "AI_Traffic_Part2_Kazakh.docx"
