def translate_text(text):
    """Мәтінді орысшадан қазақшаға аударады"""
    if not text or not text.strip():
        return text
    
    # Прямой поиск в словаре
    stripped = text.strip()
    if stripped in TRANSLATION_MAP:
        return TRANSLATION_MAP[stripped]
    
    # Проверяем литературу
    result = text
    for ru, kz in LIT_TRANSLATIONS.items():
        if ru in result:
            result = result.replace(ru, kz)
    
    return result


def translate_run_text(text):
    """Переводит текст отдельного run"""
    if not text or not text.strip():
        return text
    
    stripped = text.strip()
    
    # Проверяем в основном словаре
    if stripped in TRANSLATION_MAP:
        # Сохраняем ведущие/завершающие пробелы
        leading = text[:len(text) - len(text.lstrip())]
        trailing = text[len(text.rstrip()):]
        return leading + TRANSLATION_MAP[stripped] + trailing
    
    # Литература
    result = text
    for ru, kz in LIT_TRANSLATIONS.items():
        if ru in result:
            result = result.replace(ru, kz)
    
    return result


