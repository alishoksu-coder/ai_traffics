    print("📖 Құжатты оқу...")
    doc = Document(src_path)
    
    translated_count = 0
    total_count = 0
    
    for para in doc.paragraphs:
        full_text = para.text.strip()
        if not full_text:
            continue
            
        total_count += 1
        
        # Проверяем весь параграф целиком в словаре
        if full_text in TRANSLATION_MAP:
            kz_text = TRANSLATION_MAP[full_text]
            # Если один run — заменяем текст
            if len(para.runs) == 1:
                para.runs[0].text = kz_text
                translated_count += 1
            elif len(para.runs) > 1:
                # Объединяем все runs в один с форматированием первого
                first_run = para.runs[0]
                first_run.text = kz_text
                for r in para.runs[1:]:
                    r.text = ""
                translated_count += 1
            continue
        
        # Пытаемся перевести по частям (runs)
        any_translated = False
        for run in para.runs:
            original = run.text
            translated = translate_run_text(original)
            if translated != original:
                run.text = translated
                any_translated = True
        
        if any_translated:
            translated_count += 1
    
    print(f"📊 Барлығы: {total_count} параграф, аударылды: {translated_count}")
    
    # Сохраняем
    doc.save(dst_path)
    print(f"✅ Қазақша файл сақталды: {dst_path}")


