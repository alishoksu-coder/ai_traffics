def replace_text(find_t, replace_t):
    word.Selection.HomeKey(Unit=6)
    f = word.Selection.Find
    f.ClearFormatting()
    f.Replacement.ClearFormatting()
    f.Text = find_t
    f.Replacement.Text = replace_t
    f.Forward = True
    f.Wrap = 1
    f.MatchCase = False
    f.Execute(Replace=2)

